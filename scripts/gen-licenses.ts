// Regenerates THIRD_PARTY_LICENSES.md from every production dependency (direct
// and transitive) plus the bundled font. Run: npm run licenses
import { execFileSync } from 'node:child_process'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

interface Tree { version?: string; path?: string; dependencies?: Record<string, Tree> }

const tree: Tree = JSON.parse(execFileSync('npm', ['ls', '--omit=dev', '--all', '--long', '--json'], { encoding: 'utf8' }))
const pkgs = new Map<string, string>() // "name@version" -> install path
const walk = (deps: Record<string, Tree> = {}) => {
  for (const [name, d] of Object.entries(deps)) {
    if (!d.path || pkgs.has(`${name}@${d.version}`)) continue
    pkgs.set(`${name}@${d.version}`, d.path)
    walk(d.dependencies)
  }
}
walk(tree.dependencies)

const blocked = [...pkgs.keys()].filter((k) => /^(tldraw|@tldraw\/)/.test(k))
if (blocked.length) throw new Error(`tldraw is not allowed (PLAN.md section 5): ${blocked.join(', ')}`)

const sections = [...pkgs].sort(([a], [b]) => a.localeCompare(b)).map(([key, dir]) => {
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f))
  const text = file ? readFileSync(join(dir, file), 'utf8').trim() : `(no license file shipped; package.json declares ${pkg.license})`
  return `## ${key}\n\nLicense: ${pkg.license ?? 'UNKNOWN'}\n\n\`\`\`\n${text}\n\`\`\`\n`
})

const font = 'public/fonts/Excalifont-OFL.txt'
if (existsSync(font)) sections.push(`## Excalifont (font)\n\nLicense: OFL-1.1\n\n\`\`\`\n${readFileSync(font, 'utf8').trim()}\n\`\`\`\n`)

const summary = new Map<string, number>()
for (const [, dir] of pkgs) {
  const l = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')).license ?? 'UNKNOWN'
  summary.set(l, (summary.get(l) ?? 0) + 1)
}

writeFileSync(
  'THIRD_PARTY_LICENSES.md',
  `# Third-party licenses

Generated by \`npm run licenses\`; do not edit by hand. Lists every package shipped
in the app (direct and transitive) and the bundled font. Dev-only tools are not shipped
and are not listed.

Summary: ${[...summary].map(([l, n]) => `${l} (${n})`).join(', ')}, OFL-1.1 (1 font)

${sections.join('\n')}`,
)
console.log(`wrote THIRD_PARTY_LICENSES.md: ${pkgs.size} packages; ${[...summary].map(([l, n]) => `${l} ${n}`).join(', ')}`)
